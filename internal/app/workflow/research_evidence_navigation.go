type researchRecordLocation struct {
	NodeID       string `json:"nodeId"`
	StepID       string `json:"stepId"`
	Attempt      int    `json:"attempt"`
	OutputSHA256 string `json:"outputSha256"`
	Pointer      string `json:"pointer"`
	Offset       int    `json:"offset,omitempty"`
	EndOffset    int    `json:"endOffset,omitempty"`
}

type researchCitationNavigation struct {
	EvidencePointer     string `json:"evidencePointer"`
	QuotePointer        string `json:"quotePointer"`
	IndexedDocument     string `json:"indexedDocumentPointer,omitempty"`
	CandidateID         string `json:"candidateId,omitempty"`
	BibliographyPointer string `json:"bibliographyPointer,omitempty"`
	ImportPointer       string `json:"importPointer,omitempty"`
	BindingStatus       string `json:"bindingStatus"`
}

type researchScreeningNavigation struct {
	RecordLocation researchRecordLocation `json:"recordLocation"`
	RecordCount    int                    `json:"recordCount"`
	DecisionCounts map[string]int         `json:"decisionCounts"`
}

type researchEvidenceNavigation struct {
	Version           string                       `json:"version"`
	Citations         []researchCitationNavigation `json:"citations"`
	ScreeningRecords  *researchScreeningNavigation `json:"screeningRecords,omitempty"`
	CandidateDecision *researchRecordLocation      `json:"candidateDecision,omitempty"`
	MaterialImports   *researchRecordLocation      `json:"materialImports,omitempty"`
}

func researchEvidenceNavigationPrompt(detail RunDetail, step Step, node CompiledNode) string {
	if !isIndependentReviewSchema(node.OutputSchema) && !usesReportProvenance(node) && node.ID != "method_selection" {
		return ""
	}
	var input map[string]json.RawMessage
	if json.Unmarshal(step.Input, &input) != nil || len(input["evidenceContext"]) == 0 && len(input["evidenceScreening"]) == 0 && len(input["evidenceSelectionAudit"]) == 0 {
		return ""
	}
	if _, _, ok := parseResearchHandoff(step.Input); ok {
		// The identical index is already frozen inside stage_input. Avoid
		// multiplying a large prompt for report and the next review.
		return researchEvidenceInterpretationInstruction
	}
	return researchEvidenceInterpretationInstruction + "\n<research_evidence_navigation>\n" + string(mustJSON(compactResearchEvidenceNavigation(buildResearchEvidenceNavigation(detail, step)))) + "\n</research_evidence_navigation>\n"
}

// Repeated long pointers and source IDs belong in the diagnostic projection,
// not ten times in a nearly full model context. Array indices refer to the
// exact same immutable records; no evidence or decisions are summarized away.
func compactResearchEvidenceNavigation(index researchEvidenceNavigation) any {
	type binding struct {
		Evidence     int    `json:"evidence"`
		Document     *int   `json:"document"`
		Bibliography *int   `json:"bibliography"`
		Material     *int   `json:"material"`
		Status       string `json:"status"`
	}
	ordinal := func(pointer string) *int {
		parts := strings.Split(pointer, "/")
		// evidencePointer is the array element, others may point to an element
		// or a specific field. All are generated by the host, never parsed from
		// an untrusted filename or guessed reference marker.
		var number int
		if len(parts) < 2 {
			return nil
		}
		if _, err := fmt.Sscanf(parts[len(parts)-1], "%d", &number); err != nil {
			return nil
		}
		return &number
	}
	bindings := []binding{}
	for _, c := range index.Citations {
		evidence := ordinal(c.EvidencePointer)
		if evidence == nil {
			continue
		}
		bindings = append(bindings, binding{*evidence, ordinal(c.IndexedDocument), ordinal(c.BibliographyPointer), ordinal(c.ImportPointer), c.BindingStatus})
	}
	// The compact catalog is injected into an executing stage prompt. Keep
	// cross-stage locations navigable with the legacy offset reader, but do not
	// expose the internal JSON pointer: pointer addressing is intentionally
	// restricted to the CURRENT stage_input by the v9 execution contract. A
	// model copying that pointer together with stage_output/nodeId would turn a
	// valid navigation hint into TOOL_INVOCATION_FAILED.
	compactLocation := func(location *researchRecordLocation) *struct {
		Section      string `json:"section"`
		NodeID       string `json:"nodeId"`
		Offset       int    `json:"offset,omitempty"`
		EndOffset    int    `json:"endOffset,omitempty"`
		OutputSHA256 string `json:"outputSha256"`
	} {
		if location == nil {
			return nil
		}
		return &struct {
			Section      string `json:"section"`
			NodeID       string `json:"nodeId"`
			Offset       int    `json:"offset,omitempty"`
			EndOffset    int    `json:"endOffset,omitempty"`
			OutputSHA256 string `json:"outputSha256"`
		}{"stage_output", location.NodeID, location.Offset, location.EndOffset, location.OutputSHA256}
	}
	type screening struct {
		RecordLocation *struct {
			Section      string `json:"section"`
			NodeID       string `json:"nodeId"`
			Offset       int    `json:"offset,omitempty"`
			EndOffset    int    `json:"endOffset,omitempty"`
			OutputSHA256 string `json:"outputSha256"`
		} `json:"recordLocation"`
		RecordCount    int            `json:"recordCount"`
		DecisionCounts map[string]int `json:"decisionCounts"`
	}
	// One shared root per channel; import material indices are relative to the
	// saved materialImports record, not to stage_input.
	return struct {
		Version           string            `json:"version"`
		Roots             map[string]string `json:"roots"`
		Bindings          []binding         `json:"bindings"`
		ScreeningRecords  *screening        `json:"screeningRecords,omitempty"`
		CandidateDecision any               `json:"candidateDecision,omitempty"`
		MaterialImports   any               `json:"materialImports,omitempty"`
	}{index.Version, map[string]string{"evidence": "/evidenceContext", "document": "/researchSourceContext/indexedMaterials/documents", "bibliography": "/researchSourceContext/bibliography", "material": "/structured/materials"}, bindings,
		func() *screening {
			if index.ScreeningRecords == nil {
				return nil
			}
			return &screening{RecordLocation: compactLocation(&index.ScreeningRecords.RecordLocation), RecordCount: index.ScreeningRecords.RecordCount, DecisionCounts: index.ScreeningRecords.DecisionCounts}
		}(), compactLocation(index.CandidateDecision), compactLocation(index.MaterialImports)}
}

func recordLocation(step Step, pointer string) researchRecordLocation {
	location := researchRecordLocation{NodeID: step.NodeID, StepID: step.ID, Attempt: step.Attempt, OutputSHA256: hashJSON(step.Output), Pointer: pointer}
	if pointer == "" {
		location.EndOffset = len([]rune(string(step.Output)))
	}
	// Navigate the actual persisted characters, not a re-marshaled copy. The
	// existing task reader already accepts character offsets and returns a hash.
	if pointer != "" && strings.Count(pointer, "/") == 1 {
		location.Offset, location.EndOffset = researchOutputFieldOffsets(step.Output, strings.TrimPrefix(pointer, "/"))
	}
	return location
}

func researchOutputFieldOffsets(output json.RawMessage, field string) (int, int) {
	decoder := json.NewDecoder(bytes.NewReader(output))
	if token, err := decoder.Token(); err != nil || token != json.Delim('{') {
		return 0, 0
	}
	for decoder.More() {
		key, err := decoder.Token()
		if err != nil {
			return 0, 0
		}
		var value json.RawMessage
		if decoder.Decode(&value) != nil {
			return 0, 0
		}
		if key == field {
			end := int(decoder.InputOffset())
			return len([]rune(string(output[:end-len(value)]))), len([]rune(string(output[:end])))
		}
	}
	return 0, 0
}

func buildResearchEvidenceNavigation(detail RunDetail, step Step) researchEvidenceNavigation {
	index := researchEvidenceNavigation{Version: researchEvidenceNavigationVersion, Citations: []researchCitationNavigation{}}
	var input struct {
		Evidence []struct {
			DocumentID   string `json:"documentId"`
			AttachmentID string `json:"attachmentId"`
		} `json:"evidenceContext"`
		Source struct {
			Bibliography []struct {
				ID string `json:"id"`
			} `json:"bibliography"`
			Materials struct {
				Documents []struct {
					ID           string `json:"id"`
					AttachmentID string `json:"attachmentId"`
				} `json:"documents"`
			} `json:"indexedMaterials"`
		} `json:"researchSourceContext"`
	}
	if json.Unmarshal(step.Input, &input) != nil {
		return index
	}
	// Use only completed earlier stages in this generation. Never fall back to
	// past execution attempts, similarly named files or a pending import.
	imports := map[string][]struct {
		candidate string
		pointer   string
	}{}
	for _, earlier := range detail.Steps {
		if earlier.Status != StepCompleted || earlier.Ordinal >= step.Ordinal {
			continue
		}
		switch earlier.NodeID {
		case "evidence_import":
			var output struct {
				Structured struct {
					Materials []struct {
						CandidateID  string `json:"candidateId"`
						AttachmentID string `json:"attachmentId"`
					} `json:"materials"`
				} `json:"structured"`
			}
			if json.Unmarshal(earlier.Output, &output) != nil {
				continue
			}
			location := recordLocation(earlier, "/structured")
			index.MaterialImports = &location
			for i, material := range output.Structured.Materials {
				if strings.TrimSpace(material.AttachmentID) != "" && strings.TrimSpace(material.CandidateID) != "" {
					imports[material.AttachmentID] = append(imports[material.AttachmentID], struct {
						candidate string
						pointer   string
					}{material.CandidateID, fmt.Sprintf("/structured/materials/%d", i)})
				}
			}
		case "candidate_screening":
			var output struct {
				Manifest []struct {
					Decision string `json:"decision"`
				} `json:"evidenceManifest"`
			}
			if json.Unmarshal(earlier.Output, &output) != nil || output.Manifest == nil {
				continue
			}
			counts := map[string]int{}
			for _, record := range output.Manifest {
				counts[record.Decision]++
			}
			index.ScreeningRecords = &researchScreeningNavigation{RecordLocation: recordLocation(earlier, "/evidenceManifest"), RecordCount: len(output.Manifest), DecisionCounts: counts}
		case "candidate_review":
			location := recordLocation(earlier, "")
			index.CandidateDecision = &location
		}
	}
	for i, citation := range input.Evidence {
		entry := researchCitationNavigation{EvidencePointer: fmt.Sprintf("/evidenceContext/%d", i), QuotePointer: fmt.Sprintf("/evidenceContext/%d/quote", i), BindingStatus: "missing_import"}
		attachment := citation.AttachmentID
		matches := 0
		for j, document := range input.Source.Materials.Documents {
			if citation.DocumentID != "" && citation.DocumentID == document.ID {
				matches++
				entry.IndexedDocument = fmt.Sprintf("/researchSourceContext/indexedMaterials/documents/%d", j)
				if attachment != "" && attachment != document.AttachmentID {
					entry.BindingStatus = "conflicting_identity"
				}
				attachment = document.AttachmentID
			}
		}
		if matches > 1 || entry.BindingStatus == "conflicting_identity" {
			entry.BindingStatus, entry.IndexedDocument = "conflicting_identity", ""
		} else if citation.DocumentID != "" && matches == 0 {
			entry.BindingStatus = "missing_indexed_document"
		} else if imported := imports[attachment]; len(imported) > 1 {
			entry.BindingStatus = "ambiguous_import"
		} else if len(imported) == 1 {
			entry.CandidateID, entry.ImportPointer = imported[0].candidate, imported[0].pointer
			entry.BindingStatus = "missing_bibliography"
			matches = 0
			for j, candidate := range input.Source.Bibliography {
				if candidate.ID == entry.CandidateID {
					matches++
					entry.BibliographyPointer = fmt.Sprintf("/researchSourceContext/bibliography/%d", j)
				}
			}
			if matches == 1 {
				entry.BindingStatus = "matched"
				if citation.DocumentID == "" {
					entry.BindingStatus = "matched_attachment_only"
				}
			} else if matches > 1 {
				entry.BindingStatus, entry.BibliographyPointer = "ambiguous_bibliography", ""
			}
		}
		index.Citations = append(index.Citations, entry)
	}
	return index
}
